def dump(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def prepare():
    frozen = [{k: v for k, v in case.items() if k != 'reference'} for case in CASES]
    targets = {'cases.json': frozen,
               'references.json': {c['case_id']: c['reference'] for c in CASES},
               'protocol.json': {'version': 'PM20-choice-1', 'source': 'https://docs.typesafe.ai/api',
                                 'wire': 'model + state + questions[type=choice, instructions, criteria]',
                                 'responses': 'model + answers[choice, probabilities, confidence] + usage',
                                 'case_count': 2, 'max_calls': 2, 'retries': 0,
                                 'scope': 'self-authored synthetic protocol smoke; no accuracy or bank benefit claim',
                                 'default_demo_changed': False, 'bank_connected': False}}
    for name, obj in targets.items():
        path = OUT / name
        if path.exists():
            assert json.loads(path.read_text(encoding='utf-8')) == obj, 'Frozen protocol changed'
        else:
            dump(path, obj)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--run', action='store_true')
    args = parser.parse_args()
    prepare()
    try:
        configuration()
    except JevError as exc:
        print(json.dumps({'status': 'pending', 'reason': exc.kind, 'requests': 0}))
        return 2 if args.run else 0
    if not args.run:
        print('CONFIGURATION_PRESENT; requests=0; use --run for the frozen two-case smoke')
        return 0
    run = OUT / ('run_' + datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ'))
    run.mkdir()
    manifest = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                for p in OUT.glob('*.py')}
    dump(run / 'manifest.json', {'scripts': manifest, 'cases_sha256': hashlib.sha256((OUT/'cases.json').read_bytes()).hexdigest(),
                                 'started_at': datetime.now(timezone.utc).isoformat()})
    records = []
    for case in CASES:
        questions = {case['task_id']: case['question']}
        # Persist only the frozen synthetic request; never headers or exceptions.
        dump(run / (case['case_id'] + '.request.json'), {'state': case['state'], 'questions': questions})
        try:
            payload, result = evaluate(case['state'], questions)
            record = {'case_id': case['case_id'], 'task_id': case['task_id'],
                      'status': 'measured', **result,
                      'reference_agreement': result['answers'][case['task_id']]['choice'] == case['reference'],
                      'evidence_refs': ['m1:p1', 'm2:p1'],
                      'evidence_origin': 'synthetic material index, not generated by Jev',
                      'routing_action': 'human_review', 'auto_approval': False}
            dump(run / (case['case_id'] + '.request.json'), payload)
        except JevError as exc:
            record = {'case_id': case['case_id'], 'task_id': case['task_id'], 'status': 'failed',
                      'error_type': exc.kind, 'http_status': exc.status, 'routing_action': 'human_review'}
        records.append(record)
        dump(run / (case['case_id'] + '.response.redacted.json'), record)
        print(json.dumps({k: record.get(k) for k in ('case_id','status','error_type','latency_ms','reference_agreement')}, ensure_ascii=False))
        if record['status'] == 'failed':
            break
    summary = {'records': records, 'attempted_requests': len(records),
               'successful_requests': sum(r['status'] == 'measured' for r in records),
               'reported_input_tokens': sum(r.get('usage', {}).get('input_tokens', 0) for r in records),
               'reported_output_tokens': sum(r.get('usage', {}).get('output_tokens', 0) for r in records),
               'failed_request_usage': 'unknown unless returned; excluded from reported totals',
               'bank_connected': False, 'scope': 'two synthetic protocol smoke cases; not an accuracy estimate'}
    dump(run / 'usage_summary.json', summary)
    print('RESULT_DIRECTORY=' + str(run))
    return 0 if summary['successful_requests'] == 2 else 1


if __name__ == '__main__':
    sys.exit(main())
